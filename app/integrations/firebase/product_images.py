"""Private Firebase/GCS objects. No public download tokens or browser credentials."""
import re
from uuid import uuid4
from functools import lru_cache
import firebase_admin
from firebase_admin import credentials, storage
from google.api_core.exceptions import NotFound
from app.core.config import get_settings

MAX_BYTES = 5 * 1024 * 1024

class StorageUnavailable(Exception):
    pass

@lru_cache(maxsize=4)
def _bucket(name):
    # ADC supports GOOGLE_APPLICATION_CREDENTIALS or an attached workload identity.
    account_file = get_settings().google_application_credentials
    identity = credentials.Certificate(account_file) if account_file else credentials.ApplicationDefault()
    app = firebase_admin.initialize_app(identity, {'storageBucket': name}, name='product-images-' + str(uuid4()))
    return storage.bucket(app=app)

def bucket():
    name = get_settings().firebase_storage_bucket
    if not name:
        raise StorageUnavailable('Firebase Storage não configurado.')
    return _bucket(name)

def put_image(company_id, product_id, contents):
    try:
        key = f'companies/{company_id}/products/{product_id}/{uuid4()}.webp'
        blob = bucket().blob(key)
        blob.cache_control = 'private, no-store'
        blob.upload_from_string(contents, content_type='image/webp', if_generation_match=0, timeout=15, retry=None)
        return key, str(blob.generation)
    except Exception:
        raise StorageUnavailable('Não foi possível enviar a imagem ao Firebase.') from None

def validate_key(company_id, product_id, key, generation):
    prefix = f'companies/{company_id}/products/{product_id}/'
    if not key.startswith(prefix) or not re.fullmatch(r'[a-f0-9-]{36}\.webp', key[len(prefix):]) or not re.fullmatch(r'[0-9]{1,40}', generation or ''):
        raise StorageUnavailable('Referência de imagem inválida.')

def read_image(company_id, product_id, key, generation):
    validate_key(company_id, product_id, key, generation)
    try:
        # Only objects generated by our encoder are reachable; also bound the read.
        contents = bucket().blob(key, generation=int(generation)).download_as_bytes(start=0, end=MAX_BYTES, timeout=15, retry=None)
        if len(contents) > MAX_BYTES:
            raise StorageUnavailable('Imagem excede o limite.')
        return contents
    except NotFound:
        return None
    except Exception:
        raise StorageUnavailable('Não foi possível carregar a imagem.') from None

def delete_image(company_id, product_id, key, generation):
    validate_key(company_id, product_id, key, generation)
    try:
        bucket().blob(key, generation=int(generation)).delete(if_generation_match=int(generation), timeout=10, retry=None)
    except NotFound:
        pass
    except Exception:
        raise StorageUnavailable('Não foi possível excluir a imagem anterior.') from None
